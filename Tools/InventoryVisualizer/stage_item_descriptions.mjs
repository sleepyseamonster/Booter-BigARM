import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const directory=process.argv[2];
const plan=JSON.parse(await fs.readFile(`${directory}/plan.json`,'utf8'));
const wb=Workbook.create();
const sheet=wb.worksheets.add('Items');
for(const c of plan.changes)sheet.getRange(c.address).values=[[c.value]];
const review=wb.worksheets.add('Review');
const every=Math.max(1,Math.floor(plan.items.length/15));
const sample=plan.items.filter((_,i)=>i%every===0).slice(0,16);
review.getRange(`A1:B${sample.length+1}`).values=[['Item','Description'],...sample.map(i=>[i.name,i.description])];
review.getRange(`A1:A${sample.length+1}`).format.columnWidth=30;
review.getRange(`B1:B${sample.length+1}`).format.columnWidth=95;
review.getRange(`A1:B${sample.length+1}`).format.wrapText=true;
review.getRange(`A2:B${sample.length+1}`).format.rowHeight=105;
review.getRange('A1:B1').format.rowHeight=25;
await (await SpreadsheetFile.exportXlsx(wb)).save(`${directory}/authored.xlsx`);
const blob=await wb.render({sheetName:'Review',range:`A1:B${sample.length+1}`,scale:1,format:'png'});
await fs.writeFile(`${directory}/review.png`,new Uint8Array(await blob.arrayBuffer()));
console.log(`Authored ${plan.items.length} description edits; rendered ${sample.length} varied examples.`);
