import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const directory=process.argv[2];
const plan=JSON.parse(await fs.readFile(`${directory}/plan.json`,'utf8'));
const wb=Workbook.create();
for(const name of new Set(plan.changes.map(c=>c.sheet)))wb.worksheets.add(name);
for(const c of plan.changes.filter(c=>!c.cachedOnly))wb.worksheets.getItem(c.sheet).getRange(c.address).values=[[c.value]];
const review=wb.worksheets.add('Review');
const sample=plan.items.filter((_,i)=>i%6===0).slice(0,16);
review.getRange(`A1:B${sample.length+1}`).values=[['Prepared stock item','Description'],...sample.map(i=>[i.name,i.description])];
review.getRange(`A1:A${sample.length+1}`).format.columnWidth=32;
review.getRange(`B1:B${sample.length+1}`).format.columnWidth=100;
review.getRange(`A1:B${sample.length+1}`).format.wrapText=true;
review.getRange(`A2:B${sample.length+1}`).format.rowHeight=100;
review.getRange('A1:B1').format.rowHeight=25;
await (await SpreadsheetFile.exportXlsx(wb)).save(`${directory}/authored.xlsx`);
const img=await wb.render({sheetName:'Review',range:`A1:B${sample.length+1}`,scale:1,format:'png'});
await fs.writeFile(`${directory}/review.png`,new Uint8Array(await img.arrayBuffer()));
console.log(`Authored ${plan.counts.renamed} name revisions and ${plan.counts.descriptions} descriptions; ${plan.counts.removalProposals} proposals remain untouched.`);
